"""
حدس دسته‌ی هم‌ورق از روی داده‌ی کتاب‌شناسی (موضوع‌ها و رده‌ی دیویی کتابخانه‌ی ملی/خانه‌ی کتاب).

اول موضوع‌ها (دقیق‌ترن: «داستان‌های فارسی»، «ادبیات کودکان»، «موفقیت -- جنبه‌های روان‌شناسی»)، بعد رده‌ی دیویی.
خروجی فقط پیشنهاده؛ کاربر می‌تونه عوضش کنه. اگه چیزی نخوند None (بهتر از حدس غلط).
"""

import re

from common.text import normalize

# ترتیب مهمه: «ادبیات کودکان -- داستان» باید «کودک» بشه نه «رمان»
SUBJECT_RULES = [
    ("کودک و نوجوان", ("کودکان", "نوجوانان", "ادبیات کودک", "کتاب کودک")),
    ("داستان کوتاه", ("داستان‌های کوتاه", "داستان کوتاه", "داستانک")),
    ("شعر", ("شعر", "دیوان", "غزل", "رباعی", "مثنوی")),
    ("رمان", ("داستان", "رمان")),
    ("زندگینامه", ("سرگذشتنامه", "زندگی‌نامه", "زندگینامه", "خاطرات", "سرگذشت")),
    ("روان‌شناسی", ("روان‌شناسی", "روانشناسی", "موفقیت", "خودسازی", "شخصیت", "انگیزش", "خودیاری", "شادکامی")),
    ("فلسفه", ("فلسفه", "منطق")),
    ("دین و معنویت", ("اسلام", "قرآن", "شیعه", "دین", "عرفان", "حدیث", "دعا", "معنویت", "امامان")),
    ("اقتصاد و مدیریت", ("اقتصاد", "مدیریت", "بازاریابی", "سرمایه‌گذاری", "کسب و کار", "کارآفرینی", "بورس", "حسابداری")),
    ("کامپیوتر", ("کامپیوتر", "رایانه", "برنامه‌نویسی", "نرم‌افزار", "اینترنت", "هوش مصنوعی", "پایگاه داده")),
    ("هنر", ("هنر", "نقاشی", "موسیقی", "سینما", "عکاسی", "معماری", "خوشنویسی", "تئاتر")),
    ("جامعه‌شناسی", ("جامعه‌شناسی", "علوم اجتماعی", "علوم سیاسی", "سیاست")),
    ("تاریخ", ("تاریخ",)),
    ("علمی", ("فیزیک", "شیمی", "زیست", "ریاضی", "نجوم", "پزشکی", "علوم", "طبیعت")),
    ("درسی و دانشگاهی", ("کنکور", "آزمون", "کتاب‌های درسی", "راهنمای آموزشی", "تست", "آموزش زبان")),
]
_RULES = [(cat, tuple(normalize(w) for w in words)) for cat, words in SUBJECT_RULES]


def _dewey_number(raw):
    """«۱۵۸/۱»، «895.735»، «891/553[ج]» ← 158.1 / 895.735 / 891.553 (یا None)."""
    text = normalize(raw or "").replace("/", ".")
    m = re.search(r"\d{3}(?:\.\d+)?", text)
    return float(m.group()) if m else None


def from_dewey(raw):
    n = _dewey_number(raw)
    if n is None:
        return None
    major = int(n)
    if 4 <= major <= 6:
        return "کامپیوتر"
    if 150 <= major <= 159:
        return "روان‌شناسی"
    if 100 <= major <= 199:
        return "فلسفه"
    if 200 <= major <= 299:
        return "دین و معنویت"
    if 330 <= major <= 339 or 650 <= major <= 659:
        return "اقتصاد و مدیریت"
    if 370 <= major <= 379 or 400 <= major <= 499:
        return "درسی و دانشگاهی"
    if 300 <= major <= 399:
        return "جامعه‌شناسی"
    if 500 <= major <= 699:
        return "علمی"
    if 700 <= major <= 799:
        return "هنر"
    if 800 <= major <= 899:
        # ادبیات: رقم «قالب» — ۱ شعر، ۳ داستان. ۸۱۰–۸۸۹ رقم سوم؛ ۸۹x (زبان‌های دیگه: ۸۹۱٫۷۳ روسی، ۸۹۵٫۷۳ کره‌ای) رقم پنجم؛
        # فارسی (۸۹۱٫۵۵x) کد زبانش یه رقم بیشتره، پس رقم ششم
        digits = re.sub(r"\D", "", f"{n:.6f}")
        form = digits[2] if major < 890 else digits[5] if digits.startswith("89155") else digits[4]
        return {"1": "شعر", "3": "رمان"}.get(form)
    if 920 <= major <= 929:
        return "زندگینامه"
    if 900 <= major <= 999:
        return "تاریخ"
    return None


def guess_category_name(subjects=(), dewey="", title=""):
    text = " | ".join(normalize(s) for s in (subjects or []) if s)
    if text:
        for cat, words in _RULES:
            if any(w in text for w in words):
                return cat
    return from_dewey(dewey)


def guess_category(subjects=(), dewey="", title=""):
    """Category یا None (فقط دسته‌هایی که تو سایت وجود دارن)."""
    from .models import Category

    name = guess_category_name(subjects, dewey, title)
    return Category.objects.filter(name=name).first() if name else None
